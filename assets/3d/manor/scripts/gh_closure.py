"""温室与主楼交接处的补墙（10-16 用户发现没有围合）：11 第 8 节 exec 它；30_patch_greenhouse_closure.py 在已保存的 manor.blend 上补同样的几何。

原来缺的：① 西面主楼北墙以北（N 11.40—13.45）只有矮墙，上面没有竖框、横框和玻璃；② 南、北两面的玻璃与横框从 X 19.50 起，
贴着主楼的 0.3 m 一条竖缝是空的；③ 南面、西面矮墙与主楼墙面之间各有 5 cm 的缝。
补的件都单独成物体（温室_补框、温室_补玻璃、温室_补墙），不改原来的几个物体；与原件之间留 2—3 mm，不共面。
需要：Mesh、make、MATS（'iron'、'ghglass'、'dressed'）与目标集合 col。
"""
def greenhouse_closure(col):
    gz, zb = 3.6, 3.6 + 0.64
    def zr(x): return 6.25 + (x - 19.21) / 2.99 * 0.92                  # 西坡屋面玻璃在 x 处的标高（11：从 X 19.21、+6.25 坡到屋脊）
    ZT = 6.30                                                             # 补的最上一道横框（低于屋面）
    Fi, Fg, Fs = Mesh('iron'), Mesh('ghglass'), Mesh('dressed')
    def post(x, y, w=0.022): Fi.box(x - w, x + w, y - w, y + w, zb, zr(x + w) - 0.012)
    # ① 西面（X 19.35），从主楼北墙面 N 11.40 到西北角 N 13.45
    for y in (11.43, 11.93, 12.44, 12.94):
        post(19.35, y)
    post(19.35, 13.45)                                                    # 西北角柱（北面的竖框从 X 19.50 起）
    for zz in (zb, gz + 2.0, ZT):
        Fi.box(19.31, 19.39, 11.402, 13.425, zz - 0.022, zz + 0.022)       # 西面横框
        Fi.box(19.375, 19.47, 13.413, 13.487, zz - 0.021, zz + 0.021)      # 北面横框补到角柱
        Fi.box(19.203, 19.47, 7.713, 7.787, zz - 0.021, zz + 0.021)          # 南面横框补到主楼墙面
    post(19.226, 7.75)                                                     # 南面贴主楼的竖框
    Fg.prism([(19.346, 11.41), (19.354, 11.41), (19.354, 13.44), (19.346, 13.44)], zb + 0.03, zr(19.346) - 0.012)    # 西面玻璃
    for y, x0 in ((13.45, 19.36), (7.75, 19.25)):                         # 北面角上、南面贴主楼各一条：顶边顺着屋面
        Fg.extrude([(x0, zb + 0.03), (19.495, zb + 0.03), (19.495, zr(19.495) - 0.012), (x0, zr(x0) - 0.012)], y - 0.004, y + 0.004, 'y')
    # ③ 矮墙与主楼墙面之间的缝（石块离两边原件 3 mm）
    Fs.box(19.203, 19.252, 7.603, 7.897, gz - 0.177, gz + 0.547)
    Fs.box(19.203, 19.497, 11.403, 11.448, gz - 0.177, gz + 0.547)
    return [make(Fi, '温室_补框', col), make(Fg, '温室_补玻璃', col, recalc=False), make(Fs, '温室_补墙', col)]
